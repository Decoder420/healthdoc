export function resolveDepartment(departmentId: string) {
  return departments.find((department) => department.id === departmentId);
}

export function toDoctorFormInput(doctor: DoctorProfile): DoctorFormInput {
  return {
    name: doctor.name,
    email: doctor.email,
    phone: doctor.phone,
    gender: doctor.gender,
    departmentId: doctor.departmentId,
    specialization: doctor.specialization,
    qualification: doctor.qualification,
    experienceYears: doctor.experienceYears,
    consultationFee: doctor.consultationFee,
    licenseNumber: doctor.licenseNumber,
    status: doctor.status,
    joiningDate: doctor.joiningDate,
    address: doctor.address,
    photo: doctor.photo,
    availability: {
      days: [...doctor.availability.days],
      startTime: doctor.availability.startTime,
      endTime: doctor.availability.endTime,
    },
  };
}
