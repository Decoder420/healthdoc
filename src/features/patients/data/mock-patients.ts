export function normalizePatientRecord(patient: Partial<Patient> & Pick<Patient, "uhid" | "name" | "age" | "gender" | "phone" | "address" | "registeredAt">): Patient {
  return {
    alternateMobile: patient.alternateMobile ?? "",
    email: patient.email ?? "",
    photo: patient.photo ?? "",
    aadhaar: patient.aadhaar ?? "",
    abha: patient.abha ?? "",
    guardian: patient.guardian ?? { ...emptyGuardianDetails },
    identityDocument: patient.identityDocument ?? { ...emptyIdentityDocument },
    ...patient,
  };
}
